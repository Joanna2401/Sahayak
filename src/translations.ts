/**
 * Universal fallback builder: if a language is not pre-translated,
 * generate a clean, readable translation dictionary matching the requested language.
 */
export function getTranslationsForLang(langCode: string): PageTranslations {
  if (TRANSLATIONS[langCode]) {
    return TRANSLATIONS[langCode];
  }
  // Try 2-letter prefix match (e.g. 'es-MX' -> 'es')
  const base = langCode.split('-')[0].toLowerCase();
  if (TRANSLATIONS[base]) {
    return TRANSLATIONS[base];
  }
  return TRANSLATIONS.en;
}
